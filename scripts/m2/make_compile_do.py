"""Review M1/M2 sweep (2026-10-03): one compile script per parallel simulation worker.

Two vsim batches that share one library collide (vsim-1962, see scripts/metrics/compile_active_design_b.do),
so every worker of run_m2_sweep.py gets its own library work_m2_<k>, compiled from the CURRENT
tb/compile_active_design.do with only the library name changed (the older _b/_c/_d copies predate the R15
N-way cores and are not used).

    python scripts/m2/make_compile_do.py <workers>      -> scripts/m2/compile_m2_<k>.do, k = 1..workers
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
src = (ROOT / "tb" / "compile_active_design.do").read_text(encoding="utf-8")
n = int(sys.argv[1])
# optional prefix: work_m2f_ for the R16 FAST_HIT libraries (compiled from the R16 hdl/)
pfx = sys.argv[2] if len(sys.argv) > 2 else "work_m2_"
for k in range(1, n + 1):
    lib = "%s%d" % (pfx, k)
    s = src
    s = re.sub(r"\[file exists work\]", "[file exists %s]" % lib, s)
    s = re.sub(r"vdel -lib work -all", "vdel -lib %s -all" % lib, s)
    s = re.sub(r"^vlib work\s*$", "vlib %s" % lib, s, flags=re.M)
    s, nv = re.subn(r"^vlog -sv", "vlog -work %s -sv" % lib, s, flags=re.M)
    assert nv >= 3, nv
    assert "vlib %s" % lib in s and "vdel -lib %s -all" % lib in s
    assert not re.search(r"^vlog (?!-work %s)" % lib, s, flags=re.M), "a vlog line without -work"
    hdr = ("# Generated by scripts/m2/make_compile_do.py from tb/compile_active_design.do: library %s for\n"
           "# parallel worker %d of the review M1/M2 sweep (two batches in one library collide: vsim-1962).\n" % (lib, k))
    (ROOT / "scripts" / "m2" / ("compile_%s.do" % lib[5:])).write_text(hdr + s, encoding="utf-8", newline="\n")
    print("wrote scripts/m2/compile_%s.do (%d vlog commands)" % (lib[5:], nv))
