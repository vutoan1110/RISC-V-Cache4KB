#!/usr/bin/env python3
"""Side-by-side ASIC comparison of the three 4 KiB cache organisations (FLOW_JOURNAL Incident 96).

    python scripts/metrics/asic_compare.py DM=soc_dm_4kb:r14F_A:r14F_B SA2=soc_sa2_4kb:sa2F_A:sa2F_B \
                                           DM_VC4=soc_vc4_4kb:vc4F_A:vc4F_B [--out results/asic_compare.md]

For each design: the flow metrics merged over every step's state_out.json in step order (later steps win), the
double-execution check (A vs B on every shared flow metric except runtime / flow__), the signoff gate first
(DRC, LVS, XOR, overlaps, antenna, hold), then timing per corner from STAPostPNR (the STAMidPNR ss/ff values
are stale pre-PnR numbers and are not used), area, and vectorless power per corner from the STAPostPNR
power.rpt files (method stated in the table). Activity-based power (GLS -> SAIF) is a separate table.
"""
import argparse
import glob
import json
import math
import os

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
CORNERS = ("nom_tt_025C_1v80", "max_tt_025C_1v80", "nom_ss_100C_1v60", "max_ss_100C_1v60",
           "nom_ff_n40C_1v95", "min_ff_n40C_1v95")


def metrics(design, tag):
    base = os.path.join(R, "asic", design, "runs", tag)
    m = {}
    for so in sorted(glob.glob(os.path.join(base, "*", "state_out.json"))):
        try:
            m.update(json.load(open(so)).get("metrics", {}))
        except Exception:
            pass
    return base, m


def power(base, corner):
    sta = sorted(glob.glob(os.path.join(base, "*-openroad-stapostpnr")))
    if not sta:
        return None
    p = os.path.join(sta[-1], corner, "power.rpt")
    if not os.path.isfile(p):
        return None
    for ln in open(p):
        if ln.startswith("Total"):
            f = ln.split()
            return 1e3 * float(f[4]), 1e3 * float(f[1]), 1e3 * float(f[2]), 1e3 * float(f[3])
    return None


def f(v, nd=3):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return str(v) if v is not None else "n/a"
    if math.isnan(x):
        return "n/a"
    return ("%.*f" % (nd, x)) if nd else "%d" % round(x)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("designs", nargs="+", help="LABEL=design_dir:tagA[:tagB]")
    ap.add_argument("--out", default=os.path.join(R, "results", "asic_compare.md"))
    a = ap.parse_args()
    cols, data = [], {}
    for spec in a.designs:
        lab, rest = spec.split("=", 1)
        parts = rest.split(":")
        design, ta = parts[0], parts[1]
        tb = parts[2] if len(parts) > 2 else None
        base, m = metrics(design, ta)
        rep = "single run"
        if tb:
            _, m2 = metrics(design, tb)
            shared = [k for k in m if k in m2 and not k.startswith(("runtime", "flow__"))]
            diff = [k for k in shared if m[k] != m2[k]]
            rep = ("A = B on %d metrics" % len(shared)) if not diff else ("A != B: %d of %d differ (%s)"
                                                                           % (len(diff), len(shared), ", ".join(diff[:6])))
        cols.append(lab)
        data[lab] = (design, ta, tb, base, m, rep)
    out = ["# ASIC comparison: DM vs SA2 vs DM_VC4 (4 KiB caches, 16 KiB RAM, sky130A hd, 20 ns)", "",
           "Generated by scripts/metrics/asic_compare.py from the OpenLane run directories.", ""]
    hdr = "| | " + " | ".join(cols) + " |"
    sep = "|---|" + "---:|" * len(cols)

    def table(title, rows):
        out.extend(["## " + title, "", hdr, sep])
        for lab, fn in rows:
            out.append("| %s | %s |" % (lab, " | ".join(fn(data[c]) for c in cols)))
        out.append("")

    g = lambda k, nd=3: (lambda d: f(d[4].get(k, "n/a"), nd))
    table("Runs", [("design / runs", lambda d: "%s %s%s" % (d[0], d[1], (" + " + d[2]) if d[2] else "")),
                   ("double execution", lambda d: d[5])])
    table("Signoff gate (must be 0)", [
        ("Magic DRC", g("magic__drc_error__count", 0)), ("KLayout DRC", g("klayout__drc_error__count", 0)),
        ("Route DRC", g("route__drc_errors", 0)), ("LVS errors", g("design__lvs_error__count", 0)),
        ("XOR differences", g("design__xor_difference__count", 0)),
        ("Illegal overlaps", g("magic__illegal_overlap__count", 0)),
        ("Antenna violating nets", g("antenna__violating__nets", 0)),
        ("Hold violations (all corners)", g("timing__hold_vio__count", 0))])
    rows = []
    for c in CORNERS:
        rows.append(("setup WS %s (ns)" % c, g("timing__setup__ws__corner:" + c)))
    for c in ("nom_ss_100C_1v60", "max_ss_100C_1v60"):
        rows.append(("setup TNS %s (ns)" % c, g("timing__setup__tns__corner:" + c, 1)))
    for c in ("nom_tt_025C_1v80", "min_ff_n40C_1v95"):
        rows.append(("hold WS %s (ns)" % c, g("timing__hold__ws__corner:" + c)))
    table("Timing (STAPostPNR; SRAM macros have TT liberty only, so ss/ff are optimistic through them)", rows)
    table("Area", [("die area (um2)", g("design__die__area", 0)), ("core area (um2)", g("design__core__area", 0)),
                   ("std-cell area (um2)", g("design__instance__area__stdcell", 0)),
                   ("macro area (um2)", g("design__instance__area__macros", 0)),
                   ("macro count", g("design__instance__count__macros", 0)),
                   ("std-cell count", g("design__instance__count__stdcell", 0)),
                   ("std-cell utilisation", g("design__instance__utilization")),
                   ("wirelength (um)", g("route__wirelength", 0))])

    def pw(c, i):
        return lambda d: (f(power(d[3], c)[i], 2) if power(d[3], c) else "n/a")
    table("Power, vectorless (OpenSTA default activity; NOT the activity-based number)", [
        ("total nom_tt (mW)", pw("nom_tt_025C_1v80", 0)), ("internal nom_tt (mW)", pw("nom_tt_025C_1v80", 1)),
        ("switching nom_tt (mW)", pw("nom_tt_025C_1v80", 2)), ("leakage nom_tt (mW)", pw("nom_tt_025C_1v80", 3)),
        ("total nom_ss (mW)", pw("nom_ss_100C_1v60", 0)), ("total nom_ff (mW)", pw("nom_ff_n40C_1v95", 0))])
    open(a.out, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
