"""R14 == R15 for the DM ASIC (CACHE_CONFIG 0), formally (FLOW_JOURNAL / NHAT_KY 2026-10-02).

R15 adds hdl/cache/{d,i}cache_nway_core.v and one generate branch (CACHE_CONFIG >= 4) to icache.v / dcache.v.
For configuration 0 nothing of that is elaborated, but the R15 ASIC netlist is not byte-identical to R14's
(ABC is sensitive to the order of everything Yosys read), so identity of the gate netlists cannot be the proof.
This script proves the two RTL elaborations equivalent instead: gold = the R14 file list of
soc_dm_4kb/config_R14_FINAL.json, gate = the R15 list of config_R15_synth.json, both read the way OpenLane
reads them (-D__openlane__, SRAM macros as blackboxes), proc + flatten + memory_map, then
equiv_make / equiv_simple / equiv_induct / equiv_status -assert.

    python asic/equiv/r15_eq/make_r15_eq.py   -> asic/equiv/r15_eq/r15_eq.ys
"""
import json
from pathlib import Path

A = Path(__file__).resolve().parents[2]          # .../asic
WSL = "/mnt/e/Projects/RISCV-research/asic"
D = A / "soc_dm_4kb"


def files(cfg):
    out = []
    for f in json.load(open(D / cfg, encoding="utf-8"))["VERILOG_FILES"]:
        assert f.startswith("dir::")
        p = (D / f[5:]).resolve()
        assert p.is_file(), p
        out.append(WSL + "/" + p.relative_to(A).as_posix())
    return out


MACROS = [WSL + "/soc_dm_4kb/macros/verilog/sky130_sram_1kbyte_1rw1r_32x256_8.v",
          WSL + "/soc_dm_4kb/macros/verilog/sky130_sram_2kbyte_1rw1r_32x512_8.v"]


def side(name, cfg):
    return "\n".join([
        "# ---- %s: %s" % (name, cfg),
        "read_verilog -lib " + " ".join(MACROS),
        "read_verilog -sv -D__openlane__ " + " ".join(files(cfg)),
        "hierarchy -check -top soc_asic_top",
        "proc",
        "flatten",
        "opt_clean",
        "memory -nomap",
        "memory_map",
        # equiv_simple's SAT models have no asynchronous-reset flops; same transform on both sides
        "async2sync",
        "opt_clean",
        "rename soc_asic_top %s" % name,
        "design -stash %s" % name,
    ])


ys = "\n".join([
    "# generated by make_r15_eq.py -- do not edit",
    side("gold", "config_R14_FINAL.json"),
    side("gate", "config_R15_synth.json"),
    "design -copy-from gold -as gold gold",
    "design -copy-from gate -as gate gate",
    "equiv_make gold gate equiv",
    "hierarchy -top equiv",
    "equiv_simple -seq 2",
    "equiv_induct",
    "tee -o %s/equiv/r15_eq/equiv_status.txt equiv_status" % WSL,
    "equiv_status -assert",
    "",
])
(A / "equiv" / "r15_eq" / "r15_eq.ys").write_text(ys, encoding="utf-8", newline="\n")
print("wrote r15_eq.ys:", len(files("config_R14_FINAL.json")), "gold files,", len(files("config_R15_synth.json")), "gate files")
