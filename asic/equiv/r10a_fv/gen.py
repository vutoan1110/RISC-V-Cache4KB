"""R10a formal proof harness generator (NHAT_KY_RTL 2026-09-26).

Claim: in every reachable state of the R10a icache (controller + tag RAM),
    hot_hit == hot_valid[h] && valid_bits[request_index] && hot_tag[h] == block
i.e. the new hot hit equals the pre-R10a formula. The pre-R10a design is the
R10a design with hot_hit computed by that formula and without the hot_mvalid
register (which feeds nothing else), so equality in every reachable state
makes the two designs produce identical traces for identical inputs.

Proof: k-induction (yosys `sat -tempinduct`) of three assertions:
  A1  for every hot entry e: hot_mvalid[e] == valid_bits[line index of e]
  A2  state == ST_LOOKUP  ->  lookup_valid_q == valid_bits[miss_index]
  A3  the claim above (follows from A1)
The live RTL is copied, never edited: each module is renamed and gets extra
output ports (fv_*) that only expose existing internal signals.

    python gen.py <research root> <outdir> [--mutant]
--mutant drops the tag-write upkeep of hot_mvalid (negative control: the
proof must FAIL).
"""
import os
import re
import sys

root, out = sys.argv[1], sys.argv[2]
mutant = "--mutant" in sys.argv
os.makedirs(out, exist_ok=True)


def rd(p):
    return open(os.path.join(root, p), newline="").read().replace("\r\n", "\n")


# ---- controller copy: rename, expose internals
c = rd("hdl/cache/icache_controller.v")
assert c.count("module icache_controller #(") == 1
c = c.replace("module icache_controller #(", "module icache_controller_fv #(")
anchor = "    output wire [31:0]            data_wr_data\n);"
assert c.count(anchor) == 1
c = c.replace(anchor,
              "    output wire [31:0]            data_wr_data,\n"
              "    // fv_* : existing internal signals exposed for the proof\n"
              "    output wire [L0_ENTRIES-1:0]  fv_hot_mvalid,\n"
              "    output wire [L0_ENTRIES-1:0]  fv_hot_valid,\n"
              "    output wire [L0_ENTRIES*28-1:0] fv_hot_block,\n"
              "    output wire [2:0]             fv_state,\n"
              "    output wire                   fv_lookup_valid_q,\n"
              "    output wire [INDEX_WIDTH-1:0] fv_miss_index,\n"
              "    output wire                   fv_hot_hit,\n"
              "    output wire [27:0]            fv_request_block\n);")
expose = """
// ---- fv: exposure only (generated by asic/equiv/r10a_fv/gen.py)
assign fv_hot_mvalid     = hot_mvalid;
assign fv_hot_valid      = hot_valid;
assign fv_state          = state;
assign fv_lookup_valid_q = lookup_valid_q;
assign fv_miss_index     = miss_index;
assign fv_hot_hit        = hot_hit;
assign fv_request_block  = request_block;
genvar fv_e;
generate for(fv_e = 0; fv_e < L0_ENTRIES; fv_e = fv_e + 1) begin : g_fv
    wire [L0_IDX_BITS-1:0] fv_idx = fv_e;
    assign fv_hot_block[fv_e*28 +: 28] = {hot_tag[fv_e], fv_idx};
end endgenerate
"""
end = c.rindex("endmodule")
c = c[:end] + expose + c[end:]
# the translate_off $fatal guard is simulation-only; keep yosys -formal quiet
c = re.sub(r"// synthesis translate_off\n(.*?)// synthesis translate_on\n", "", c, flags=re.S)
if mutant:
    old = "    else if(tag_wr_en && hot_holds_miss_line)"
    assert c.count(old) == 1
    c = c.replace(old, "    else if(1'b0 && tag_wr_en && hot_holds_miss_line)  // MUTANT")
open(os.path.join(out, "icache_controller_fv.v"), "w", newline="\n").write(c)

# ---- tag RAM copy: rename, expose valid_bits
t = rd("hdl/cache/icache_tag_ram.v")
assert t.count("module icache_tag_ram #(") == 1
t = t.replace("module icache_tag_ram #(", "module icache_tag_ram_fv #(")
anchor = "    input  wire                   wr_valid\n);"
assert t.count(anchor) == 1
t = t.replace(anchor, "    input  wire                   wr_valid,\n"
                      "    output wire [LINE_COUNT-1:0]  fv_valid_bits\n);")
end = t.rindex("endmodule")
t = t[:end] + "assign fv_valid_bits = valid_bits;  // fv exposure\n" + t[end:]
open(os.path.join(out, "icache_tag_ram_fv.v"), "w", newline="\n").write(t)

# ---- harness: wired exactly as hdl/cache/icache.v g_dm_baseline, free inputs
top = """// R10a proof harness (generated). Free inputs; controller + tag RAM wired
// as in hdl/cache/icache.v (g_dm_baseline). The data RAM is outside the claim
// (its read line only reaches hot_line / rsp_data), so data_rd_line is free.
module fv_top #(parameter LINE_COUNT = 256, parameter L0_ENTRIES = 8)(
    input wire clk, input wire reset_n,
    input wire req_valid, input wire [31:0] req_addr,
    input wire refill_req_ready, input wire refill_rsp_valid,
    input wire [31:0] refill_rsp_data, input wire refill_rsp_last, input wire refill_rsp_error,
    input wire [127:0] data_rd_line
);
localparam INDEX_WIDTH = $clog2(LINE_COUNT);
localparam TAG_WIDTH   = 32 - 4 - INDEX_WIDTH;
localparam L0B         = (L0_ENTRIES > 1) ? $clog2(L0_ENTRIES) : 1;
wire [INDEX_WIDTH-1:0] tag_rd_index, tag_wr_index, data_rd_index, data_wr_index, tag_valid_rd_index;
wire [TAG_WIDTH-1:0] tag_rd_tag, tag_wr_tag;
wire tag_rd_en, tag_valid_rd, tag_wr_en, tag_wr_valid, data_wr_en, data_rd_en;
wire [1:0] data_wr_word; wire [31:0] data_wr_data;
wire req_ready, rsp_valid, rsp_error, refill_req_valid, access_event, hit_event, miss_event;
wire [31:0] rsp_data, refill_req_addr, access_count, hit_count, miss_count;
wire [L0_ENTRIES-1:0] hot_mvalid, hot_valid; wire [L0_ENTRIES*28-1:0] hot_block;
wire [2:0] state; wire lookup_valid_q; wire [INDEX_WIDTH-1:0] miss_index;
wire hot_hit; wire [27:0] request_block; wire [LINE_COUNT-1:0] valid_bits;

icache_controller_fv #(.INDEX_WIDTH(INDEX_WIDTH),.TAG_WIDTH(TAG_WIDTH),.L0_ENTRIES(L0_ENTRIES)) u_ctrl(
    .clk(clk),.reset_n(reset_n),.req_valid(req_valid),.req_addr(req_addr),
    .req_ready(req_ready),.rsp_valid(rsp_valid),.rsp_data(rsp_data),.rsp_error(rsp_error),
    .refill_req_valid(refill_req_valid),.refill_req_addr(refill_req_addr),
    .refill_req_ready(refill_req_ready),.refill_rsp_valid(refill_rsp_valid),
    .refill_rsp_data(refill_rsp_data),.refill_rsp_last(refill_rsp_last),
    .refill_rsp_error(refill_rsp_error),.access_count(access_count),
    .hit_count(hit_count),.miss_count(miss_count),.access_event(access_event),
    .hit_event(hit_event),.miss_event(miss_event),
    .tag_rd_en(tag_rd_en),.tag_rd_index(tag_rd_index),.tag_rd_tag(tag_rd_tag),
    .tag_valid_rd_index(tag_valid_rd_index),.tag_valid_rd(tag_valid_rd),
    .tag_wr_en(tag_wr_en),.tag_wr_index(tag_wr_index),.tag_wr_tag(tag_wr_tag),.tag_wr_valid(tag_wr_valid),
    .data_rd_en(data_rd_en),.data_rd_index(data_rd_index),.data_rd_line(data_rd_line),
    .data_wr_en(data_wr_en),.data_wr_index(data_wr_index),.data_wr_word(data_wr_word),
    .data_wr_data(data_wr_data),
    .fv_hot_mvalid(hot_mvalid),.fv_hot_valid(hot_valid),.fv_hot_block(hot_block),.fv_state(state),
    .fv_lookup_valid_q(lookup_valid_q),.fv_miss_index(miss_index),.fv_hot_hit(hot_hit),
    .fv_request_block(request_block));

icache_tag_ram_fv #(.LINE_COUNT(LINE_COUNT),.INDEX_WIDTH(INDEX_WIDTH),.TAG_WIDTH(TAG_WIDTH)) u_tag(
    .clk(clk),.reset_n(reset_n),.rd_en(tag_rd_en),.rd_index(tag_rd_index),.rd_tag(tag_rd_tag),
    .valid_rd_index(tag_valid_rd_index),.valid_rd(tag_valid_rd),
    .wr_en(tag_wr_en),.wr_index(tag_wr_index),.wr_tag(tag_wr_tag),.wr_valid(tag_wr_valid),
    .fv_valid_bits(valid_bits));

// A1: each hot entry's copy equals the tag RAM valid bit of the line it holds
reg a1; integer e;
always @(*) begin
    a1 = 1'b1;
    for(e = 0; e < L0_ENTRIES; e = e + 1)
        if(hot_mvalid[e] != valid_bits[hot_block[e*28 +: INDEX_WIDTH]]) a1 = 1'b0;
end
// A2: in ST_LOOKUP (1) the latched valid bit is still the RAM's bit
wire a2 = (state != 3'd1) || (lookup_valid_q == valid_bits[miss_index]);
// A3: the R10a hot hit equals the pre-R10a formula
wire [L0B-1:0] h = request_block[L0B-1:0];
wire old_hot_hit = hot_valid[h] && valid_bits[request_block[INDEX_WIDTH-1:0]] &&
                   (hot_block[h*28 + L0B +: 28 - L0B] == request_block[27:L0B]);
wire a3 = (hot_hit == old_hot_hit);
always @(*) begin
    if(reset_n) begin
        assert(a1);
        assert(a2);
        assert(a3);
    end
end
endmodule
"""
open(os.path.join(out, "fv_top.sv"), "w", newline="\n").write(top)
print("[OK] harness in", out, "(mutant)" if mutant else "")
