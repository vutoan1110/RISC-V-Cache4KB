"""R16 (FAST_HIT, review M1) formal checks -- rule D.3: formal proof WITH a negative control.

Module level (hdl/cache wrappers, LINE_COUNT 64 and 256):
  gold = R15 (asic/snapshots/rtl_r15/hdl/cache), gate = the patched tree, CACHE_CONFIG 1 / 2 / 3 / 4,
  gate FAST_HIT = 0 -> must be EQUIVALENT (equiv_status -assert passes)
  gate FAST_HIT = 1 -> NEGATIVE CONTROL, must NOT be proved (an equivalence that also "holds" for the changed
                       behaviour would mean the method cannot see the change)
SoC level (the PD inputs): gold = the exact VERILOG_FILES of asic/<design>/config_wide.json (R14 snapshot + the
  SRAM wrapper, what every SA2 / DM_VC4 PD run read), gate = the same list with the R16 soc_top / cache files,
  FAST_HIT = 0 (default) -> must be EQUIVALENT: the PD results stay valid for R16.
Both sides are read the way the formal flows here always read them (proc, flatten, memory_map, async2sync).

    python asic/equiv/r16_eq/make_r16_eq.py <patched tree root>   -> asic/equiv/r16_eq/*.ys + run_r16_eq.sh
"""
import json
import sys
from pathlib import Path

A = Path(__file__).resolve().parents[2]                    # .../asic
R = A.parent                                               # research root
WR = "/mnt/e/Projects/RISCV-research"
D = A / "equiv" / "r16_eq"
gate_root = Path(sys.argv[1]).resolve()
# --soc-only (2026-10-06): rewrite only the SoC-level .ys + run_r16_eq_soc.sh; the module-level files stay as they ran
# (2026-10-03, gate = work_r16_dryrun, byte-identical to the frozen R16 hdl/cache)
SOC_ONLY = "--soc-only" in sys.argv[2:]
gate_wsl = WR + "/" + gate_root.relative_to(R).as_posix()
# module-level gold: hdl/cache of R15 (commit 1252e4a, git-clean), copied before R16 touched hdl/ (MD5SUMS beside it);
# the ASIC snapshot rtl_r15 lacks the FPGA-only data RAMs (icache_data_ram.v), so it cannot be the gold here
gold_wsl = WR + "/asic/equiv/r16_eq/gold_r15"

CACHE = {"icache": ["icache_tag_ram.v", "icache_controller.v", "icache_data_ram.v", "cache_dse_data_bank.v", "icache_dse_core.v",
                    "icache_nway_core.v", "icache.v"],
         "dcache": ["dcache_tag_ram.v", "dcache_controller.v", "dcache_data_ram.v", "cache_dse_data_bank.v",
                    "dcache_dse_core.v", "dcache_nway_core.v", "dcache.v"]}


def prep(top, label, params):
    ch = " ".join("-set %s %d" % kv for kv in params)
    return "\n".join(([("chparam %s %s" % (ch, top))] if params else []) + [
        "hierarchy -check -top %s" % top,
        "proc", "flatten", "opt_clean", "memory -nomap", "memory_map", "async2sync", "opt_clean",
        "rename %s %s" % (top, label), "design -stash %s" % label])


def finish(name, expect_equiv):
    st = "%s/asic/equiv/r16_eq/%s.status" % (WR, name)
    return "\n".join([
        "design -copy-from gold -as gold gold", "design -copy-from gate -as gate gate",
        "equiv_make gold gate equiv", "hierarchy -top equiv", "equiv_simple -seq 2", "equiv_induct",
        "tee -o %s equiv_status" % st,
        "equiv_status -assert" if expect_equiv else "# negative control: the runner expects equiv_status to report unproven cells",
        ""])


jobs = []
for mod, files in CACHE.items():
    for lines in (64, 256):
        for cfg in (1, 2, 3, 4):
            for fast in (0, 1):
                if fast == 1 and cfg not in (1, 4):
                    continue                               # negative control on one DSE and one N-way point
                name = "%s_cfg%d_l%d_fast%d" % (mod, cfg, lines, fast)
                gold = "read_verilog -sv " + " ".join("%s/hdl/cache/%s" % (gold_wsl, f) for f in files)
                gate = "read_verilog -sv " + " ".join("%s/hdl/cache/%s" % (gate_wsl, f) for f in files)
                base = [("LINE_COUNT", lines), ("CACHE_CONFIG", cfg)]
                ys = "\n".join(["# generated by make_r16_eq.py -- %s" % name, "design -reset", gold,
                                prep(mod, "gold", base), "design -reset", gate,
                                prep(mod, "gate", base + [("FAST_HIT", fast)]), finish(name, fast == 0)])
                if not SOC_ONLY:
                    (D / (name + ".ys")).write_text(ys, encoding="utf-8", newline="\n")
                jobs.append((name, fast == 0))

MACROS = [WR + "/asic/soc_dm_4kb/macros/verilog/sky130_sram_1kbyte_1rw1r_32x256_8.v",
          WR + "/asic/soc_dm_4kb/macros/verilog/sky130_sram_2kbyte_1rw1r_32x512_8.v"]
R16_FILES = {"hdl/soc_top.v", "hdl/cache/icache.v", "hdl/cache/dcache.v", "hdl/cache/icache_dse_core.v",
             "hdl/cache/dcache_dse_core.v"}
for des in ("soc_sa2_4kb", "soc_vc4_4kb"):
    vf = json.load(open(A / des / "config_wide.json", encoding="utf-8"))["VERILOG_FILES"]
    gold_files, gate_files = [], []
    for f in vf:
        p = (A / des / f[5:]).resolve()
        rel = p.relative_to(A).as_posix()
        gold_files.append(WR + "/asic/" + rel)
        key = rel.split("snapshots/rtl_r14/", 1)[1] if "snapshots/rtl_r14/" in rel else None
        gate_files.append("%s/%s" % (gate_wsl, key) if key in R16_FILES else WR + "/asic/" + rel)
    assert sum(1 for f in gate_files if f.startswith(gate_wsl)) == len(R16_FILES), gate_files
    # R15/R16 icache.v / dcache.v name the N-way cores in a generate branch (CACHE_CONFIG >= 4), not elaborated here
    gate_files += ["%s/hdl/cache/%s" % (gate_wsl, f) for f in ("icache_nway_core.v", "dcache_nway_core.v")]
    side = lambda fl: "\n".join(["read_verilog -lib " + " ".join(MACROS),
                                 "read_verilog -sv -D__openlane__ " + " ".join(fl)])
    # 2026-10-06: R15+ names the DSE core genblk1.g_dse (R14: g_dse), so the gate is written out, renamed by
    # rename_genblk.py (object names only) and read back before it is stashed -- otherwise no cache register pairs.
    # Negative control (SA2 only): the same gate with CACHE_FAST_HIT 1 on soc_top, from a generated copy of the
    # design's soc_asic_top.v; it must leave unproven cells, or the SoC-level method cannot see a change.
    variants = [(0, gate_files)]
    if des == "soc_sa2_4kb":
        top = A / des / "soc_asic_top.v"
        s = top.read_text(encoding="utf-8")
        old = "    .L0_ENTRIES            (8)\n) u_soc ("
        assert s.count(old) == 1, "soc_asic_top.v anchor"
        neg = D / "negctl"
        neg.mkdir(exist_ok=True)
        (neg / "soc_asic_top_fast1.v").write_text(
            "// GENERATED by make_r16_eq.py from asic/%s/soc_asic_top.v: negative control, CACHE_FAST_HIT 1\n" % des
            + s.replace(old, "    .L0_ENTRIES            (8),\n    .CACHE_FAST_HIT        (1)\n) u_soc ("),
            encoding="utf-8", newline="\n")
        top_wsl = WR + "/asic/" + top.relative_to(A).as_posix()
        assert top_wsl in gate_files
        variants.append((1, [WR + "/asic/equiv/r16_eq/negctl/soc_asic_top_fast1.v" if f == top_wsl else f
                             for f in gate_files]))
    for fast, gfiles in variants:
        name = "%s_soc_fast%d" % (des, fast)
        raw, ren = ("%s/asic/equiv/r16_eq/%s_gate_%s.il" % (WR, name, k) for k in ("raw", "renamed"))
        gate_prep = prep("soc_asic_top", "gate", []).rsplit("\n", 1)[0]          # everything but the stash
        ys = "\n".join(["# generated by make_r16_eq.py -- %s: PD file list (R14 snapshot) vs R16, FAST_HIT %d" % (name, fast),
                        "design -reset", side(gold_files), prep("soc_asic_top", "gold", []),
                        "design -reset", side(gfiles), gate_prep,
                        "write_rtlil %s" % raw,
                        "exec -expect-return 0 -- python3 %s/asic/equiv/r16_eq/rename_genblk.py %s %s" % (WR, raw, ren),
                        "design -reset", "read_rtlil %s" % ren, "design -stash gate",
                        finish(name, fast == 0)])
        (D / (name + ".ys")).write_text(ys, encoding="utf-8", newline="\n")
        jobs.append((name, fast == 0))

Y = "/nix/store/zdhr86kv5rxlp0s58rzxk1aki1igankx-yosys-with-plugins-python3-3.11.9-env/bin/yosys"
sh = ["#!/usr/bin/env bash", "# generated by make_r16_eq.py: run every R16 formal check, one line per check in r16_eq_summary.txt",
      "cd %s/asic/equiv/r16_eq" % WR, "S=r16_eq_summary.txt; : > $S"]
for name, expect in jobs:
    sh.append("%s -q -l %s.log %s.ys > /dev/null 2>&1; rc=$?" % (Y, name, name))
    # equiv_status prints "Of those cells N are proven and M are unproven." (2026-10-03: the first pattern,
    # 'Found [0-9]+ unproven', never matched "Found a total of M unproven", so every negative control read u=0)
    sh.append("u=$(grep -oE 'and [0-9]+ are unproven' %s.status 2>/dev/null | grep -oE '[0-9]+' | tail -1); u=${u:-0}" % name)
    if expect:
        sh.append("if [ $rc -eq 0 ]; then r=PASS; else r=FAIL; fi; echo \"%s expect-equivalent rc=$rc unproven=$u $r\" >> $S" % name)
    else:
        sh.append("if [ \"$u\" -gt 0 ]; then r=PASS; else r=FAIL; fi; echo \"%s negative-control rc=$rc unproven=$u $r\" >> $S" % name)
sh.append("cat $S; grep -c ' PASS$' $S; ! grep -q ' FAIL$' $S")
if not SOC_ONLY:
    (D / "run_r16_eq.sh").write_text("\n".join(sh) + "\n", encoding="utf-8", newline="\n")
# 2026-10-03: two concurrent runs of the whole list (module checks + two memory-hungry SoC-level checks) coincided
# with the WSL VM going down at 08:22; split runners let the SoC checks run alone, one at a time.
for part, keep in ([] if SOC_ONLY else [("mod", lambda n: not n.startswith("soc_"))]) + [("soc", lambda n: n.startswith("soc_"))]:
    body = sh[:3] + ["S=r16_eq_summary_%s.txt; : > $S" % part]
    for i in range(4, len(sh) - 1, 3):
        name = sh[i].split(" -l ")[1].split(".log")[0]
        if keep(name):
            body += sh[i:i + 3]
    body.append(sh[-1])
    (D / ("run_r16_eq_%s.sh" % part)).write_text("\n".join(body) + "\n", encoding="utf-8", newline="\n")
print("%d checks -> asic/equiv/r16_eq/run_r16_eq{,_mod,_soc}.sh" % len(jobs))
