"""R16 for the DM chip (CACHE_CONFIG 0), formally: the signed-off PD input (soc_dm_4kb/config_R14_FINAL.json, what
r14F_A / r14F_B synthesised) == the R16 snapshot (config_R16_synth.json), the same method as asic/equiv/r15_eq
(read like OpenLane: -D__openlane__, SRAM macros as blackboxes; proc + flatten + memory_map + async2sync on both
sides; equiv_make / equiv_simple -seq 2 / equiv_induct / equiv_status -assert).
The method's ability to see a change is shown by the module-level negative controls of make_r16_eq.py (same
passes); the DM chip elaborates no FAST_HIT logic, so a FAST_HIT=1 control is not possible at this level.

    python asic/equiv/r16_eq/make_r16_eq_dm.py   -> dm_soc_fast0.ys + run_r16_eq_dm.sh (summary r16_eq_summary_dm.txt)
"""
import json
from pathlib import Path

A = Path(__file__).resolve().parents[2]                    # .../asic
WSL = "/mnt/e/Projects/RISCV-research/asic"
D = A / "soc_dm_4kb"
E = A / "equiv" / "r16_eq"
Y = "/nix/store/zdhr86kv5rxlp0s58rzxk1aki1igankx-yosys-with-plugins-python3-3.11.9-env/bin/yosys"


def files(cfg):
    out = []
    for f in json.load(open(D / cfg, encoding="utf-8"))["VERILOG_FILES"]:
        assert f.startswith("dir::")
        p = (D / f[5:]).resolve()
        assert p.is_file(), p
        out.append(WSL + "/" + p.relative_to(A).as_posix())
    return out


MACROS = [WSL + "/soc_dm_4kb/macros/verilog/sky130_sram_1kbyte_1rw1r_32x256_8.v",
          WSL + "/soc_dm_4kb/macros/verilog/sky130_sram_2kbyte_1rw1r_32x512_8.v"]


def side(name, cfg):
    return "\n".join(["# ---- %s: %s" % (name, cfg), "design -reset",
                      "read_verilog -lib " + " ".join(MACROS),
                      "read_verilog -sv -D__openlane__ " + " ".join(files(cfg)),
                      "hierarchy -check -top soc_asic_top", "proc", "flatten", "opt_clean", "memory -nomap",
                      "memory_map", "async2sync", "opt_clean", "rename soc_asic_top %s" % name,
                      "design -stash %s" % name])


name = "dm_soc_fast0"
ys = "\n".join(["# generated by make_r16_eq_dm.py -- %s: DM PD input (R14) vs R16" % name,
                side("gold", "config_R14_FINAL.json"), side("gate", "config_R16_synth.json"),
                "design -copy-from gold -as gold gold", "design -copy-from gate -as gate gate",
                "equiv_make gold gate equiv", "hierarchy -top equiv", "equiv_simple -seq 2", "equiv_induct",
                "tee -o %s/equiv/r16_eq/%s.status equiv_status" % (WSL, name), "equiv_status -assert", ""])
(E / (name + ".ys")).write_text(ys, encoding="utf-8", newline="\n")
sh = ["#!/usr/bin/env bash", "# generated by make_r16_eq_dm.py", "cd %s/equiv/r16_eq" % WSL,
      "S=r16_eq_summary_dm.txt; : > $S",
      "%s -q -l %s.log %s.ys > /dev/null 2>&1; rc=$?" % (Y, name, name),
      "u=$(grep -oE 'and [0-9]+ are unproven' %s.status 2>/dev/null | grep -oE '[0-9]+' | tail -1); u=${u:-0}" % name,
      "if [ $rc -eq 0 ]; then r=PASS; else r=FAIL; fi; echo \"%s expect-equivalent rc=$rc unproven=$u $r\" >> $S" % name,
      "cat $S; ! grep -q ' FAIL$' $S"]
(E / "run_r16_eq_dm.sh").write_text("\n".join(sh) + "\n", encoding="utf-8", newline="\n")
print("wrote %s.ys (%d gold files, %d gate files) + run_r16_eq_dm.sh" % (
    name, len(files("config_R14_FINAL.json")), len(files("config_R16_synth.json"))))
