#!/usr/bin/env bash
# Extended conflict probe (2026-10-08): firmware build (WSL), compile into work_cprobe (tb/compile_active_design.do
# with the library renamed, plus tb_conflict_probe.sv), then CACHE_CONFIG 0-5 at 4 KiB (256 lines, SPAN 4096: the
# design point) and 1 KiB (64 lines, SPAN 1024: the published Table 6 geometry), every run twice. Each run is
# checked window by window against the independent cache model (model_windows.py), and pass 1 must equal pass 2
# field for field. Output: results/conflict_probe/ and results/conflict_probe.csv (pass 1, all runs).
#   bash sw_metrics/conflict/run_conflict_probe.sh        (Git Bash on Windows, from anywhere)
set -uo pipefail
cd "$(dirname "$0")/../.."
V=C:/questasim64_2024.1/win64/vsim.exe
OUT=results/conflict_probe
mkdir -p "$OUT"
fail=0
wsl.exe -d Ubuntu -e bash -lc 'cd /mnt/e/Projects/RISCV-research/sw_metrics/conflict && make clean > /dev/null && make 2>&1' > "$OUT/build.log" 2>&1
[ "$(grep -c '\[PASS\] no DIV' "$OUT/build.log")" -eq 2 ] || { echo "[FAIL] firmware build, see $OUT/build.log"; exit 1; }
python - <<'PY'
import re
s = open("tb/compile_active_design.do", newline="").read()
s = s.replace("[file exists work]", "[file exists work_cprobe]").replace("vdel -lib work -all", "vdel -lib work_cprobe -all")
s = re.sub(r"^vlib work\s*$", "vlib work_cprobe", s, flags=re.M)
s = re.sub(r"^vlog -sv", "vlog -work work_cprobe -sv", s, flags=re.M)
assert not re.search(r"^vlog (?!-work work_cprobe)", s, flags=re.M)
s += "\nvlog -work work_cprobe -sv sw_metrics/conflict/tb_conflict_probe.sv\n"
open("results/conflict_probe/compile_cprobe.do", "w", newline="\n").write(
    "# Generated by sw_metrics/conflict/run_conflict_probe.sh from tb/compile_active_design.do (library work_cprobe)\n" + s)
PY
"$V" -c -do "do results/conflict_probe/compile_cprobe.do; quit -f" > "$OUT/compile.log" 2>&1
grep -q '\[PASS\] Active RTL' "$OUT/compile.log" && ! grep -qE '\*\* (Error|Fatal)' "$OUT/compile.log" \
    || { echo "[FAIL] compile, see $OUT/compile.log"; exit 1; }
for pass in 1 2; do
  for lines in 256 64; do
    if [ $lines -eq 256 ]; then hexf=sw_metrics/conflict/conflict_probe_4k_rv32.hex; else hexf=sw_metrics/conflict/conflict_probe_1k_rv32.hex; fi
    for cfg in 0 1 2 3 4 5; do
      b=cfg${cfg}_l${lines}_p$pass
      "$V" -c -do "vsim -onfinish stop -gCACHE_CONFIG=$cfg -gICACHE_LINE_COUNT=$lines -gDCACHE_LINE_COUNT=$lines -gMEMFILE=$hexf work_cprobe.tb_conflict_probe +trace=$OUT/trace_$b.txt +max_cycles=40000000; run -all; quit -f" > "$OUT/$b.log" 2>&1
      python sw_metrics/conflict/model_windows.py "$OUT/$b.log" "$OUT/trace_$b.txt" $cfg $lines "$OUT/$b.csv" || fail=$((fail+1))
    done
  done
done
for f in "$OUT"/cfg*_p1.csv; do
  cmp -s "$f" "${f%_p1.csv}_p2.csv" || { echo "[FAIL] pass 1 != pass 2: $f"; fail=$((fail+1)); }
done
python - <<'PY'
import csv, glob
rows = []
for f in sorted(glob.glob("results/conflict_probe/cfg*_p1.csv")):
    rows += list(csv.DictReader(open(f, newline="")))
w = csv.DictWriter(open("results/conflict_probe.csv", "w", newline=""), fieldnames=list(rows[0]))
w.writeheader(); w.writerows(rows)
print("results/conflict_probe.csv: %d windows" % len(rows))
PY
rm -f "$OUT"/trace_*_p2.txt
echo "conflict probe: $fail failure(s)"
exit $fail
