#ifndef PLATFORM_COUNTER_MAP_H
#define PLATFORM_COUNTER_MAP_H

// Canonical system-monitor register map.
#undef SYSMON_I_HIT
#undef SYSMON_I_MISS
#undef SYSMON_D_HIT
#undef SYSMON_D_MISS
#undef SYSMON_TRAP
#undef SYSMON_MCAUSE
#undef SYSMON_MCYCLE
#undef SYSMON_MINSTRET
#undef SYSMON_LDSTSTALL
#undef SYSMON_BRFLUSH
#undef SYSMON_ISTALL
#undef SYSMON_DSTALL

#define SYSMON_REG(offset)      (*(volatile unsigned int *)(SYSMON_BASE + (offset)))
#define SYSMON_ID               SYSMON_REG(0x00)
#define SYSMON_CONTROL_STATUS   SYSMON_REG(0x04)
#define SYSMON_SNAPSHOT_SEQ     SYSMON_REG(0x08)
#define SYSMON_LAST_MCAUSE      SYSMON_REG(0x0C)
#define SYSMON_MCYCLE           SYSMON_REG(0x10)
#define SYSMON_CYCLE_RETIRE     SYSMON_REG(0x14)
#define SYSMON_CYCLE_LOAD_USE   SYSMON_REG(0x18)
#define SYSMON_CYCLE_IWAIT      SYSMON_REG(0x1C)
#define SYSMON_CYCLE_DWAIT      SYSMON_REG(0x20)
#define SYSMON_CYCLE_CONTROL    SYSMON_REG(0x24)
#define SYSMON_CYCLE_TRAP       SYSMON_REG(0x28)
#define SYSMON_CYCLE_MMIO       SYSMON_REG(0x2C)
#define SYSMON_CYCLE_FILL_DRAIN SYSMON_REG(0x30)
#define SYSMON_CYCLE_OTHER      SYSMON_REG(0x34)
#define SYSMON_MINSTRET         SYSMON_REG(0x40)
#define SYSMON_I_ACCESS         SYSMON_REG(0x44)
#define SYSMON_I_HIT            SYSMON_REG(0x48)
#define SYSMON_I_MISS           SYSMON_REG(0x4C)
#define SYSMON_DREAD_ACCESS     SYSMON_REG(0x50)
#define SYSMON_DREAD_HIT        SYSMON_REG(0x54)
#define SYSMON_DREAD_MISS       SYSMON_REG(0x58)
#define SYSMON_DWRITE_ACCESS    SYSMON_REG(0x5C)
#define SYSMON_DWRITE_HIT       SYSMON_REG(0x60)
#define SYSMON_DWRITE_MISS      SYSMON_REG(0x64)
#define SYSMON_CONTROL_EVENTS   SYSMON_REG(0x68)
#define SYSMON_MISPREDICTS      SYSMON_REG(0x6C)
#define SYSMON_TRAP_EVENTS      SYSMON_REG(0x70)
#define SYSMON_AXI_READ_TXNS    SYSMON_REG(0x74)
#define SYSMON_AXI_WRITE_TXNS   SYSMON_REG(0x78)
#define SYSMON_REASON_LIVE      SYSMON_REG(0x7C)

#define SYSMON_CMD_CLEAR_START          0x01u
#define SYSMON_CMD_SNAPSHOT             0x02u
#define SYSMON_CMD_FREEZE_SNAPSHOT      0x03u
#define SYSMON_CMD_UNFREEZE             0x04u
#define SYSMON_CMD_CLEAR_FROZEN         0x05u
#define SYSMON_CMD_INVALIDATE_SNAPSHOT  0x06u

#endif
